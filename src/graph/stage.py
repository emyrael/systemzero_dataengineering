"""Pipeline stage: build the graph, load it into SurrealDB, run the sample queries."""

from __future__ import annotations

import asyncio
from datetime import date, datetime, timezone
from pathlib import Path
from typing import Any

import pandas as pd
from loguru import logger
from surrealdb import AsyncSurreal, RecordID

from src.cleaning.clean import CLEAN_SUBDIR
from src.graph.loader import connect, load_graph, log_load, wire
from src.graph.model import EDGE_TABLES, NODE_TABLES, Graph, build_graph
from src.graph.queries import QUERIES, as_rows, pearson_r
from src.utils.config import PROJECT_ROOT, PipelineConfig

SILVER_TABLES = ("vendors", "products", "customers", "transactions", "invoices", "invoice_lines",
                 "support_tickets", "product_reviews", "call_transcripts")
GOLD_TABLES = ("customer_features", "product_features", "vendor_features", "invoice_features")
REPORT_FILE = "graph_queries.md"
MAX_ROWS = 10


def read_tables(config: PipelineConfig) -> tuple[dict[str, pd.DataFrame], dict[str, pd.DataFrame]]:
    silver = {n: pd.read_parquet(config.paths.silver_dir / CLEAN_SUBDIR / f"{n}.parquet") for n in SILVER_TABLES}
    gold = {n: pd.read_parquet(config.paths.gold_dir / f"{n}.parquet") for n in GOLD_TABLES}
    return silver, gold


def query_params(gold: dict[str, pd.DataFrame], as_of: date) -> dict[str, Any]:
    """Example subjects chosen from the data: the highest-CLV customer and top-revenue product."""
    customers = gold["customer_features"].sort_values(["customer_lifetime_value", "customer_id"], ascending=[False, True])
    products = gold["product_features"].sort_values(["revenue_contribution", "product_id"], ascending=[False, True])
    return {
        "customer": RecordID("customer", customers["customer_id"].iloc[0]),
        "product": RecordID("product", products["product_id"].iloc[0]),
        "as_of": datetime(as_of.year, as_of.month, as_of.day, tzinfo=timezone.utc),
    }


async def run_queries(db: AsyncSurreal, params: dict[str, Any]) -> dict[str, list[dict[str, Any]]]:
    return {q.id: as_rows(await db.query(q.surql, wire(params))) for q in QUERIES}


def _cell(v: Any) -> str:
    if isinstance(v, RecordID):
        return f"{v.table_name}:{v.id}"
    if isinstance(v, datetime):
        return v.date().isoformat()
    if isinstance(v, float):
        return f"{v:,.2f}"
    if isinstance(v, list):
        return "; ".join(_cell(x) for x in v)
    if isinstance(v, dict):
        return ", ".join(f"{_cell(x)}" for x in v.values())
    return "–" if v is None else str(v).replace("|", "\\|")


def _table(rows: list[dict[str, Any]]) -> list[str]:
    if not rows:
        return ["*(no rows)*"]
    columns = list(dict.fromkeys(k for r in rows for k in r))
    shown = rows[:MAX_ROWS]
    lines = ["| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    lines += ["| " + " | ".join(_cell(r.get(c)) for c in columns) + " |" for r in shown]
    if len(rows) > MAX_ROWS:
        lines.append(f"\n*{len(rows) - MAX_ROWS} more rows not shown.*")
    return lines


def render_report(results: dict[str, list[dict[str, Any]]], params: dict[str, Any], counts: dict[str, int],
                  graph: Graph, url: str) -> str:
    out = [
        "# Graph Queries", "",
        f"Generated by `python run_pipeline.py` against `{url.split('://', 1)[0]}://…`. Schema: "
        "`src/graph/schema.surql`; model: `docs/GRAPH_MODEL.md`. Parameters: "
        + ", ".join(f"`${k}` = `{_cell(v)}`" for k, v in params.items()) + ".", "",
        f"Loaded **{sum(counts[t] for t in NODE_TABLES):,} nodes** and **{sum(counts[t] for t in EDGE_TABLES):,} edges**: "
        + ", ".join(f"{t} {counts[t]:,}" for t in (*NODE_TABLES, *EDGE_TABLES)) + ".", "",
        "Edges not created because one end is not a node (orphan references, kept and flagged in Silver): "
        + (", ".join(f"`{k}` {v}" for k, v in sorted(graph.skipped.items())) or "none") + ".", "",
    ]
    for number, q in enumerate(QUERIES, start=1):
        rows = results[q.id]
        out += [f"## {number}. {q.question}", "", "```sql", q.surql, "```", "", q.explanation, "", *_table(rows), ""]
        if q.id == "q8_payment_vs_sales":
            r = pearson_r([row.get("on_time_pct") for row in rows], [row.get("product_sales") for row in rows])
            out += [f"**Pearson r (on-time % vs product sales): {r}** across {len(rows)} vendors.", ""]
    return "\n".join(out)


async def _run(config: PipelineConfig, batch_id: str) -> dict[str, int]:
    silver, gold = read_tables(config)
    graph = build_graph(silver, gold, config.reference.country_regions, batch_id)
    url = config.surrealdb.endpoint(PROJECT_ROOT)
    if "://" in url and url.split("://", 1)[0] in ("surrealkv", "file"):
        Path(url.split("://", 1)[1]).parent.mkdir(parents=True, exist_ok=True)
    db = await connect(config.surrealdb, url)
    try:
        counts = await load_graph(db, graph, batch_id, config.surrealdb.batch_size)
        log_load(counts, graph)
        params = query_params(gold, config.run.as_of_date)
        results = await run_queries(db, params)
    finally:
        await db.close()
    (config.paths.output_dir / REPORT_FILE).write_text(render_report(results, params, counts, graph, url))
    logger.bind(stage="graph").info("Graph queries written", queries=len(results))
    return counts


def run_graph(config: PipelineConfig, batch_id: str) -> dict[str, int]:
    return asyncio.run(_run(config, batch_id))
